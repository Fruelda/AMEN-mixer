package main

import (
	"context"
	"fmt"

	"desktop/backend/audio"
)

// ============================================================
// APP
// ============================================================

type App struct {
	ctx context.Context

	audio *audio.Manager

	realtime *RealtimeServer
}

// ============================================================
// NEW APP
// ============================================================

func NewApp() *App {

	return &App{
		audio: audio.New(),
	}
}

// ============================================================
// STARTUP
// ============================================================

func (a *App) startup(
	ctx context.Context,
) {

	a.ctx =
		ctx

	fmt.Println(
		"===================================",
	)

	fmt.Println(
		"AMEN MIXER STARTING...",
	)

	fmt.Println(
		"===================================",
	)

	// ========================================================
	// AUDIO + WEBSOCKET
	// ========================================================

	a.setupRealtime()

	// ========================================================
	// LOCAL NETWORK DISCOVERY
	// ========================================================

	startMDNS()

	// ========================================================
	// ESP32 SERIAL
	// ========================================================

	a.startSerial()

	fmt.Println(
		"===================================",
	)

	fmt.Println(
		"AMEN MIXER READY",
	)

	fmt.Println(
		"===================================",
	)
}

// ============================================================
// GREET
// ============================================================

func (a *App) Greet(
	name string,
) string {

	return fmt.Sprintf(
		"Hello %s, It's show time!",
		name,
	)
}
