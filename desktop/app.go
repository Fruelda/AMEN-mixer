package main

import (
	"context"
	"fmt"

	"desktop/backend/audio"
)

// ============================================================
// APP
// ============================================================

type App struct {
	ctx context.Context

	audio    *audio.Manager
	realtime *RealtimeServer
}

// ============================================================
// CREATE APP
// ============================================================

func NewApp() *App {
	return &App{
		audio: audio.New(),
	}
}

// ============================================================
// STARTUP
// ============================================================

func (a *App) startup(
	ctx context.Context,
) {
	a.ctx = ctx

	fmt.Println("===================================")
	fmt.Println("AMEN MIXER STARTING...")
	fmt.Println("===================================")

	// ========================================================
	// AUDIO + WEBSOCKET
	// ========================================================

	a.setupRealtime()

	// ========================================================
	// LOCAL NETWORK DISCOVERY
	// ========================================================

	startMDNS()

	// ========================================================
	// ESP32 Wifi
	// ========================================================

	// a.startSerial()
	// a.startESP32()

	fmt.Println("===================================")
	fmt.Println("АМИНЬ READY")
	fmt.Println("===================================")
}

// ============================================================
// SHUTDOWN
// ============================================================

func (a *App) shutdown(
	_ context.Context,
) {
	// ========================================================
	// LOCAL NETWORK DISCOVERY
	// ========================================================

	stopMDNS()

	fmt.Println("[APP] AMEN MIXER STOPPED")
}
